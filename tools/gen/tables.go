// genErrorCodes writes the service-layer (data.code) table: code -> documented HTTP status and
// Korean description.
func genErrorCodes(file string) ([]byte, error) {
	raw, err := os.ReadFile(file) //nolint:gosec // G304: path of the vendored spec, given by the developer
	if err != nil {
		return nil, err
	}
	var doc struct {
		Source  string `json:"source"`
		Service []struct {
			Code          string `json:"code"`
			HTTPStatus    int    `json:"httpStatus"`
			Result        string `json:"result"`
			DescriptionKo string `json:"descriptionKo"`
		} `json:"service"`
	}
	if err := json.Unmarshal(raw, &doc); err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	w := &writer{}
	w.p("// Code generated by tools/gen from spec/error-codes.json. DO NOT EDIT.")
	w.p("")
	w.p("package bizgo")
	w.p("")
	w.p("// errorCodesSource is where the error code table was taken from.")
	w.p("const errorCodesSource = %q", doc.Source)
	w.p("")
	w.p("// serviceCodes maps service-layer codes (data.code) to their documented HTTP status and Korean description.")
	w.p("var serviceCodes = map[string]serviceCode{")
	seen := map[string]bool{}
	for _, e := range doc.Service {
		if e.Code == "" {
			return nil, fmt.Errorf("%s: service entry without code", file)
		}
		if seen[e.Code] {
			return nil, fmt.Errorf("%s: duplicate service code %s", file, e.Code)
		}
		seen[e.Code] = true
		text := e.DescriptionKo
		if text == "" {
			text = e.Result
		}
		w.p("\t%q: {%d, %q},", e.Code, e.HTTPStatus, text)
	}
	w.p("}")
	return format.Source([]byte(w.b.String()))
}

// genEUCKR writes a bitset of the BMP characters that CP949 (the superset of EUC-KR the carriers
// count with) can encode. Every such character except ASCII takes 2 bytes.
func genEUCKR() ([]byte, error) {
	enc := korean.EUCKR.NewEncoder()
	var bits [0x10000 / 64]uint64
	count := 0
	for r := rune(0); r <= 0xFFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		b, err := enc.Bytes([]byte(string(r)))
		if err != nil {
			continue
		}
		switch {
		case r < 0x80 && len(b) == 1:
		case r >= 0x80 && len(b) == 2:
		default:
			return nil, fmt.Errorf("unexpected CP949 length %d for U+%04X", len(b), r)
		}
		bits[r/64] |= 1 << (r % 64)
		count++
	}
	w := &writer{}
	w.p("// Code generated by tools/gen with golang.org/x/text/encoding/korean. DO NOT EDIT.")
	w.p("")
	w.p("package bizgo")
	w.p("")
	w.p("// cp949Count is the number of characters in cp949Bits.")
	w.p("const cp949Count = %d", count)
	w.p("")
	w.p("// cp949Bits has bit r set when CP949 can encode the BMP character r")
	w.p("// (ASCII in 1 byte, everything else in 2 bytes).")
	w.p("var cp949Bits = [%d]uint64{", len(bits))
	for i := 0; i < len(bits); i += 4 {
		var parts []string
		for _, v := range bits[i : i+4] {
			parts = append(parts, fmt.Sprintf("0x%016x", v))
		}
		w.p("\t%s,", strings.Join(parts, ", "))
	}
	w.p("}")
	return format.Source([]byte(w.b.String()))
}

// genSpecData extracts what the tests need from the spec, so the SDK's tests need no YAML parser:
// the operations with their x-sdk-* metadata, the webhooks, the schema names and the examples.
func genSpecData(spec *yaml.Node, o *opsGen) ([]byte, error) {
	type pagination struct {
		Style    string `json:"style"`
		Request  string `json:"request"`
		Size     string `json:"size,omitempty"`
		Items    string `json:"items"`
		Response string `json:"response,omitempty"`
		HasNext  string `json:"hasNext,omitempty"`
		Total    string `json:"total,omitempty"`
	}
	type operation struct {
		ID         string      `json:"id"`
		Method     string      `json:"method"`
		Path       string      `json:"path"`
		Resource   string      `json:"resource"`
		SDKMethod  string      `json:"sdkMethod"`
		Retry      string      `json:"retry"`
		Rate       string      `json:"rate"`
		Result     string      `json:"result"`
		Pagination *pagination `json:"pagination,omitempty"`
	}
	type webhook struct {
		Name    string `json:"name"`
		ID      string `json:"id"`
		Signed  bool   `json:"signed"`
		Payload string `json:"payload"`
		Example any    `json:"example,omitempty"`
	}
	type responseExample struct {
		Operation string `json:"operation"`
		Status    string `json:"status"`
		Schema    string `json:"schema"`
		Value     any    `json:"value"`
	}
	var out struct {
		SpecVersion      string            `json:"specVersion"`
		Operations       []operation       `json:"operations"`
		Webhooks         []webhook         `json:"webhooks"`
		Schemas          []string          `json:"schemas"`
		RequestExamples  map[string]any    `json:"requestExamples"`
		ResponseExamples []responseExample `json:"responseExamples"`
	}
	out.SpecVersion = str(path(spec, "info", "version"))
	out.RequestExamples = map[string]any{}
	for _, op := range o.ops {
		entry := operation{ID: op.id, Method: op.method, Path: op.path, Resource: op.resource, SDKMethod: op.sdkMethod,
			Retry: op.retry, Rate: op.rate, Result: op.resultPath}
		if pg := op.pagination; pg != nil {
			entry.Pagination = &pagination{pg.style, pg.request, pg.size, pg.items, pg.response, pg.hasNext, pg.total}
		}
		out.Operations = append(out.Operations, entry)
		if op.id == "sendOmni" {
			if ex := path(op.op, "requestBody", "content", "application/json", "examples"); ex != nil {
				for _, name := range keys(ex) {
					v, err := toAny(get(get(ex, name), "value"))
					if err != nil {
						return nil, err
					}
					out.RequestExamples[name] = v
				}
			}
		}
		responses := get(op.op, "responses")
		for _, status := range keys(responses) {
			content := path(responses, status, "content", "application/json")
			example := get(content, "example")
			schema := strings.TrimPrefix(str(path(content, "schema", "$ref")), refPrefix)
			if example == nil || schema == "" {
				continue
			}
			v, err := toAny(example)
			if err != nil {
				return nil, err
			}
			out.ResponseExamples = append(out.ResponseExamples, responseExample{op.id, status, schema, v})
		}
	}
	hooks := get(spec, "webhooks")
	for _, key := range keys(hooks) {
		op := path(hooks, key, "post")
		wh := webhook{Name: str(get(op, "x-sdk-webhook")), ID: str(get(op, "operationId")),
			Payload: refName(path(op, "requestBody", "content", "application/json", "schema"))}
		wh.Signed = o.webhookSigned(op)
		if ex := path(op, "requestBody", "content", "application/json", "example"); ex != nil {
			v, err := toAny(ex)
			if err != nil {
				return nil, err
			}
			wh.Example = v
		}
		out.Webhooks = append(out.Webhooks, wh)
	}
	sort.Slice(out.Webhooks, func(i, j int) bool { return out.Webhooks[i].Name < out.Webhooks[j].Name })
	out.Schemas = keys(path(spec, "components", "schemas"))
	sort.Strings(out.Schemas)
	data, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
