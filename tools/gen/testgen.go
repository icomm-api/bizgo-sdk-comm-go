package main

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"go.yaml.in/yaml/v3"
)

// genOpsTest writes operations_gen_test.go: one call of every generated method (and iterator) with
// valid placeholder arguments, so the test suite can check that every operation of the spec is
// reachable and sends the documented method and path.

// Placeholder values that satisfy the patterns of the spec.
var patternSamples = map[string]string{
	"^[0-9]+$":                     "1",
	"^[0-9]{11}$":                  "01000000000",
	"^[0-9]{4}-[0-9]{2}-[0-9]{2}$": "2026-01-01",
	"^[0-9]{8}$":                   "20260101",
	"^[A-Za-z0-9_]+$":              "SAMPLE",
}

func (o *opsGen) genOpsTest() ([]byte, error) {
	calls := &writer{}
	iters := &writer{}
	samples := &writer{}
	voids := &writer{}
	usesStrings := false
	usesTime := false
	for _, op := range o.ops {
		if op.handwritten {
			if op.pagination != nil {
				samples.p("\t%q: %q,", op.id, `{}`)
			}
			continue
		}
		for _, v := range o.variants(op) {
			var args []string
			for _, pp := range op.pathParams {
				args = append(args, strconv.Quote("PATH-"+pp.name))
			}
			if v.body != "" {
				bm := o.g.bySpec[v.body]
				lit, err := o.sampleModel(bm, 0)
				if err != nil {
					return nil, fmt.Errorf("%s: %w", op.id, err)
				}
				if strings.Contains(lit, "strings.NewReader") {
					usesStrings = true
				}
				args = append(args, "&"+lit)
			}
			if len(op.queryParams) > 0 {
				var fields []string
				for _, prm := range op.queryParams {
					if !prm.required {
						continue
					}
					val, err := sampleParam(prm)
					if err != nil {
						return nil, fmt.Errorf("%s: %w", op.id, err)
					}
					if strings.Contains(val, "bizgo.Date") {
						usesTime = true
					}
					fields = append(fields, prm.field+": "+val)
				}
				args = append(args, "bizgo."+paramsType(op)+"{"+strings.Join(fields, ", ")+"}")
			}
			access := "c." + o.accessPath(op.resource) + "." + v.name
			argList := "ctx"
			if len(args) > 0 {
				argList += ", " + strings.Join(args, ", ")
			}
			key := op.id
			if v.form && op.jsonBody != "" {
				key += "+files"
			}
			_, _, _, _, err := o.resolve(op.response, op.resultPath, "resp")
			void := err != nil
			calls.p("\t%q: func(ctx context.Context, c *bizgo.Client) (any, error) {", key)
			if void {
				calls.p("\t\treturn nil, %s(%s)", access, argList)
				voids.p("\t%q: true,", key)
			} else {
				calls.p("\t\treturn %s(%s)", access, argList)
			}
			calls.p("\t},")
			if op.pagination != nil && v.name == op.goMethod {
				_, _, _, it, err := o.resolve(op.response, op.pagination.items, "resp")
				if err != nil {
					return nil, err
				}
				sample := `{}`
				switch it.elem.kind {
				case kString:
					sample = `"x"`
				case kInt, kInt64, kFloat:
					sample = `1`
				case kObject, kAnyMap, kStringMap:
				default:
					return nil, fmt.Errorf("%s: no item sample", op.id)
				}
				samples.p("\t%q: %q,", op.id, sample)
				iters.p("\t%q: func(ctx context.Context, c *bizgo.Client) (int, error) {", op.id)
				iters.p("\t\tn := 0")
				iters.p("\t\tfor _, err := range c.%s.Iter%s(%s) {", o.accessPath(op.resource), op.goMethod, argList)
				iters.p("\t\t\tif err != nil {")
				iters.p("\t\t\t\treturn n, err")
				iters.p("\t\t\t}")
				iters.p("\t\t\tn++")
				iters.p("\t\t}")
				iters.p("\t\treturn n, nil")
				iters.p("\t},")
			}
		}
	}
	w := &writer{}
	w.p("// Code generated by tools/gen from spec/openapi.yaml. DO NOT EDIT.")
	w.p("")
	w.p("package bizgo_test")
	w.p("")
	w.p("import (")
	w.p("\t\"context\"")
	if usesStrings {
		w.p("\t\"strings\"")
	}
	if usesTime {
		w.p("\t\"time\"")
	}
	w.p("")
	w.p("\tbizgo \"github.com/icomm-api/bizgo-sdk-comm-go\"")
	w.p(")")
	w.p("")
	w.p("// generatedCalls calls every generated method once with valid placeholder arguments")
	w.p("// (path values are \"PATH-<name>\"). The key is the operationId (\"+files\" for the multipart variant).")
	w.p("// It returns the method's result (nil for methods without one, see generatedVoid).")
	w.p("var generatedCalls = map[string]func(context.Context, *bizgo.Client) (any, error){")
	w.b.WriteString(calls.b.String())
	w.p("}")
	w.p("")
	w.p("// generatedVoid lists the generated methods that return only an error.")
	w.p("var generatedVoid = map[string]bool{")
	w.b.WriteString(voids.b.String())
	w.p("}")
	w.p("")
	w.p("// generatedIterators walks the iterator of every generated paginated method.")
	w.p("var generatedIterators = map[string]func(context.Context, *bizgo.Client) (int, error){")
	w.b.WriteString(iters.b.String())
	w.p("}")
	w.p("")
	w.p("// pageItemSamples is one JSON item of a page of every paginated operation (generated or hand-written).")
	w.p("var pageItemSamples = map[string]string{")
	w.b.WriteString(samples.b.String())
	w.p("}")
	if usesTime {
		w.p("")
		w.p("var _ = time.January")
	}
	src := []byte(w.b.String())
	out, err := format.Source(src)
	if err != nil {
		return nil, fmt.Errorf("gofmt ops test: %w\n%s", err, src)
	}
	return out, nil
}

func sampleParam(prm param) (string, error) {
	switch prm.goType {
	case "string":
		return strconv.Quote(sampleString(prm.schema, "Q-"+prm.name)), nil
	case "time.Time":
		return "bizgo.Date(2026, time.January, 2)", nil
	case "int", "int64":
		return sampleNumber(prm.schema), nil
	case "bool":
		return "true", nil
	case "[]string":
		return "[]string{" + strconv.Quote(sampleString(get(prm.schema, "items"), "Q-"+prm.name)) + "}", nil
	}
	return "", fmt.Errorf("no sample for required parameter %s of type %s", prm.name, prm.goType)
}

func sampleString(s *yaml.Node, fallback string) string {
	if e := strs(get(s, "enum")); len(e) > 0 {
		return e[0]
	}
	if p := str(get(s, "pattern")); p != "" {
		if v, ok := patternSamples[p]; ok {
			return v
		}
		return "UNKNOWN-PATTERN " + p
	}
	if v := str(get(s, "minLength")); v != "" {
		n, _ := strconv.Atoi(v)
		return strings.Repeat("x", max(n, 1))
	}
	if v := str(get(s, "maxLength")); v != "" {
		if n, _ := strconv.Atoi(v); n < len(fallback) {
			return strings.Repeat("x", n)
		}
	}
	return fallback
}

func sampleNumber(s *yaml.Node) string {
	if v := str(get(s, "minimum")); v != "" {
		return v
	}
	if v := str(get(s, "maximum")); v != "" {
		if n, err := strconv.Atoi(v); err == nil && n < 1 {
			return v
		}
	}
	return "1"
}

// sampleModel returns a composite literal (without &) with every required field set.
func (o *opsGen) sampleModel(m *model, depth int) (string, error) {
	if depth > 8 {
		return "", fmt.Errorf("%s: required fields nest too deep", m.specName)
	}
	if m.flow != nil {
		fm := m.flow[0]
		member := o.g.byGo[fm.typeName]
		lit, err := o.sampleModel(member, depth+1)
		if err != nil {
			return "", err
		}
		return "bizgo." + m.goName + "{" + fm.field + ": &" + lit + "}", nil
	}
	var fields []string
	for _, f := range m.fields {
		if !f.required {
			continue
		}
		val, err := o.sampleValue(f.t, f.schema, f.json, depth)
		if err != nil {
			return "", fmt.Errorf("%s: %w", f.path, err)
		}
		fields = append(fields, f.goName+": "+val)
	}
	return "bizgo." + m.goName + "{" + strings.Join(fields, ", ") + "}", nil
}

func (o *opsGen) sampleValue(t typ, s *yaml.Node, name string, depth int) (string, error) {
	switch t.kind {
	case kString:
		v := sampleString(s, "x")
		if strings.HasPrefix(v, "UNKNOWN-PATTERN") {
			return "", fmt.Errorf("no sample for pattern of %s (add it to patternSamples)", name)
		}
		if phoneFields[name] {
			v = "01000000000"
		}
		return strconv.Quote(v), nil
	case kInt, kInt64, kFloat:
		return sampleNumber(s), nil
	case kBool:
		return "true", nil
	case kStringMap:
		return `map[string]string{"k": "v"}`, nil
	case kAnyMap:
		return `map[string]any{"k": "v"}`, nil
	case kFile:
		return `&bizgo.UploadFile{Reader: strings.NewReader("sample"), Filename: "sample.jpg"}`, nil
	case kObject:
		lit, err := o.sampleModel(o.g.byGo[t.name], depth+1)
		if err != nil {
			return "", err
		}
		return "&" + lit, nil
	case kFlow:
		return o.sampleModel(o.g.byGo[t.name], depth+1)
	case kArray:
		n := 1
		if v := str(get(s, "minItems")); v != "" {
			n, _ = strconv.Atoi(v)
			n = max(n, 1)
		}
		elem := *t.elem
		var one string
		switch elem.kind {
		case kObject, kFlow:
			lit, err := o.sampleModel(o.g.byGo[elem.name], depth+1)
			if err != nil {
				return "", err
			}
			one = strings.TrimPrefix(lit, "bizgo."+elem.name)
		case kFile:
			one = `{Reader: strings.NewReader("sample"), Filename: "sample.jpg"}`
		default:
			v, err := o.sampleValue(elem, get(s, "items"), name, depth)
			if err != nil {
				return "", err
			}
			one = v
		}
		items := make([]string, n)
		for i := range items {
			items[i] = one
		}
		ts := typeString(t, false)
		switch elem.kind {
		case kObject, kFlow:
			ts = "[]bizgo." + elem.name
		case kFile:
			ts = "[]bizgo.UploadFile"
		}
		return ts + "{" + strings.Join(items, ", ") + "}", nil
	}
	return "", fmt.Errorf("no sample for %s", name)
}
